"""Optional provenance recipe. Requires the original DE92 archive on this host.

The portable JSONL is committed; consumers do not need the source archive.
"""
import argparse,hashlib,json
from pathlib import Path
import numpy as np
from finshybrid.scales import PC,PS,VS,US

def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def physical(z):return np.r_[np.array(z[1:7])*PS+PC,np.array(z[7:13])*VS]
def main():
    p=argparse.ArgumentParser();p.add_argument('source',type=Path);p.add_argument('destination',type=Path);a=p.parse_args()
    a.destination.mkdir(parents=True,exist_ok=False)
    raw=a.source/'online_adaptation.jsonl'
    records=[json.loads(s) for s in raw.read_text(encoding='utf-8-sig').splitlines() if s.strip()][:80]
    assert len(records)==80
    rows=[dict(timestamp_s=records[0]['previousTime'],state=physical(records[0]['previous']).tolist())]
    for index,r in enumerate(records):
        if index:np.testing.assert_allclose(physical(r['previous']),rows[-1]['state'],atol=2e-8,rtol=0)
        assert abs(r['t']-r['previousTime']-.1)<.002
        rows.append(dict(timestamp_s=r['t'],state=physical(r['observed']).tolist(),
                         completed_mean_wrench=(np.array(r['input'])*US).tolist(),
                         expected_bias=r['velocityBias'],
                         expected_baseline_velocity=(np.array(r['baseNext'][7:13])*VS).tolist()))
    dest=a.destination/'observations.jsonl'
    dest.write_text('\n'.join(json.dumps(r,allow_nan=False) for r in rows)+'\n',encoding='utf-8')
    provenance=dict(source='DE92 preflight/fast/train281/bias_legacy_n40_f98/seed1092000/invariant-seed1092000/online_adaptation.jsonl',
                    source_sha256=sha(raw),rows='first80 completed transitions plus initial observation, no outcome selection',
                    schema='state: SI body-origin pose and body-COM velocity; completed mean wrench: SI body N/Nm',
                    expectations='native saved baseline velocity and online bias, not generated by this Python package',
                    limitations='historical simulation observations, not real robot data, not full episode or a performance comparison',
                    export_sha256=sha(dest))
    (a.destination/'provenance.json').write_text(json.dumps(provenance,indent=2),encoding='utf-8')
if __name__=='__main__':main()
